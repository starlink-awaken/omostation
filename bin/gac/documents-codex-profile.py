#!/usr/bin/env python3
"""Generate and verify the dedicated Codex profile for Documents domains."""

from __future__ import annotations

import argparse
import json
import os
import re
import selectors
import shutil
import stat
import subprocess
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_REGISTRY = (
    ROOT / ".omo" / "_truth" / "registry" / "documents-domain-projects.yaml"
)
DEFAULT_PROFILE = Path.home() / ".codex" / "documents.config.toml"
DEFAULT_CODEX = Path("/Applications/ChatGPT.app/Contents/Resources/codex")
_BARE_TOML_KEY = re.compile(r"^[A-Za-z0-9_-]+$")
_GENERATED_MARKER = "# Generated by Workspace bin/gac/documents-codex-profile.py."


class ProfileError(RuntimeError):
    """A stable, user-facing profile generation failure."""


@dataclass(frozen=True)
class ProfileContract:
    name: str
    server: str
    approval_mode: str
    allowed_tools: tuple[str, ...]


@dataclass(frozen=True)
class CodexInventory:
    mcp_servers: tuple[str, ...]
    disabled_skill_paths: tuple[str, ...]


def _workspace_root(project_registry: Path) -> Path:
    parent = project_registry.parent
    if (
        project_registry.name != "documents-domain-projects.yaml"
        or parent.name != "registry"
        or parent.parent.name != "_truth"
        or parent.parent.parent.name != ".omo"
    ):
        raise ProfileError(
            "project registry must be Workspace .omo/_truth/registry/"
            "documents-domain-projects.yaml"
        )
    return parent.parents[2].resolve(strict=True)


def _load_contract(project_registry: Path) -> ProfileContract:
    try:
        raw = yaml.safe_load(project_registry.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, yaml.YAMLError) as exc:
        raise ProfileError(f"project registry invalid: {exc}") from exc
    if not isinstance(raw, dict):
        raise ProfileError("project registry must be a mapping")

    workspace_mcp = raw.get("workspace_mcp")
    clients = raw.get("clients")
    profiles = raw.get("profiles")
    if not isinstance(workspace_mcp, dict):
        raise ProfileError("workspace_mcp must be a mapping")
    if not isinstance(clients, dict) or not isinstance(clients.get("codex"), dict):
        raise ProfileError("clients.codex must be a mapping")
    if not isinstance(profiles, dict) or not isinstance(
        profiles.get("content-domain"), dict
    ):
        raise ProfileError("profiles.content-domain must be a mapping")

    contract = clients["codex"].get("profile_contract")
    if not isinstance(contract, dict):
        raise ProfileError("clients.codex.profile_contract must be a mapping")
    expected = {
        "name": "documents",
        "owner": "workspace",
        "approval_mode": "approve",
        "skill_policy": "disable_user_local",
    }
    for field, value in expected.items():
        if contract.get(field) != value:
            raise ProfileError(
                f"clients.codex.profile_contract.{field} must be {value}"
            )

    server = workspace_mcp.get("server")
    if not isinstance(server, str) or not server:
        raise ProfileError("workspace_mcp.server must be non-empty")
    if contract.get("exclusive_mcp_server") != server:
        raise ProfileError(
            "clients.codex.profile_contract.exclusive_mcp_server must match "
            "workspace_mcp.server"
        )

    generator_ref = contract.get("generator_ref")
    if not isinstance(generator_ref, str) or not generator_ref:
        raise ProfileError(
            "clients.codex.profile_contract.generator_ref must be a "
            "Workspace-relative file"
        )
    candidate = Path(generator_ref)
    if candidate.is_absolute() or ".." in candidate.parts or "://" in generator_ref:
        raise ProfileError(
            "clients.codex.profile_contract.generator_ref must be a "
            "Workspace-relative file"
        )
    workspace = _workspace_root(project_registry)
    try:
        generator = (workspace / candidate).resolve(strict=True)
    except OSError as exc:
        raise ProfileError(
            f"clients.codex.profile_contract.generator_ref is unavailable: {generator_ref}"
        ) from exc
    if not generator.is_relative_to(workspace) or not generator.is_file():
        raise ProfileError(
            "clients.codex.profile_contract.generator_ref must be a "
            "Workspace-relative file"
        )

    profile = profiles["content-domain"]
    tools = profile.get("allowed_workspace_tools")
    if (
        not isinstance(tools, list)
        or not tools
        or not all(isinstance(item, str) and item for item in tools)
    ):
        raise ProfileError(
            "profiles.content-domain.allowed_workspace_tools must be a non-empty string list"
        )
    exposed_tools = workspace_mcp.get("read_tools")
    if not isinstance(exposed_tools, list) or not set(tools).issubset(exposed_tools):
        raise ProfileError(
            "profiles.content-domain.allowed_workspace_tools must be exposed by workspace_mcp"
        )
    return ProfileContract(
        name=contract["name"],
        server=server,
        approval_mode=contract["approval_mode"],
        allowed_tools=tuple(sorted(set(tools))),
    )


def _codex_binary(value: str | None) -> Path:
    if value:
        path = Path(value).expanduser()
    elif DEFAULT_CODEX.is_file():
        path = DEFAULT_CODEX
    elif discovered := shutil.which("codex"):
        path = Path(discovered)
    else:
        raise ProfileError("Codex CLI is unavailable")
    if not path.is_file() or not os.access(path, os.X_OK):
        raise ProfileError(f"Codex CLI is not executable: {path}")
    return path


def _mcp_inventory(codex: Path, timeout: float) -> tuple[str, ...]:
    try:
        result = subprocess.run(
            [str(codex), "mcp", "list", "--json"],
            capture_output=True,
            text=True,
            check=False,
            timeout=timeout,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise ProfileError(f"cannot inspect Codex MCP inventory: {exc}") from exc
    if result.returncode != 0:
        detail = result.stderr.strip() or f"exit {result.returncode}"
        raise ProfileError(f"cannot inspect Codex MCP inventory: {detail}")
    try:
        payload = json.loads(result.stdout)
    except json.JSONDecodeError as exc:
        raise ProfileError("Codex MCP inventory is not valid JSON") from exc
    if not isinstance(payload, list):
        raise ProfileError("Codex MCP inventory must be a list")
    names = []
    for item in payload:
        if not isinstance(item, dict) or not isinstance(item.get("name"), str):
            raise ProfileError("Codex MCP inventory contains an invalid server")
        names.append(item["name"])
    if len(names) != len(set(names)):
        raise ProfileError("Codex MCP inventory contains duplicate server names")
    return tuple(sorted(names))


def _write_message(stream: Any, message: dict[str, Any]) -> None:
    stream.write(json.dumps(message, ensure_ascii=False) + "\n")
    stream.flush()


def _read_response(
    process: subprocess.Popen[str], request_id: int, timeout: float
) -> dict[str, Any]:
    if process.stdout is None:
        raise ProfileError("Codex app-server stdout is unavailable")
    selector = selectors.DefaultSelector()
    selector.register(process.stdout, selectors.EVENT_READ)
    deadline = time.monotonic() + timeout
    try:
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0 or not selector.select(remaining):
                raise ProfileError("Codex app-server response timed out")
            line = process.stdout.readline()
            if not line:
                raise ProfileError("Codex app-server closed before responding")
            try:
                message = json.loads(line)
            except json.JSONDecodeError:
                continue
            if message.get("id") == request_id:
                if "error" in message:
                    raise ProfileError(f"Codex app-server error: {message['error']}")
                result = message.get("result")
                if not isinstance(result, dict):
                    raise ProfileError("Codex app-server returned an invalid response")
                return result
    finally:
        selector.close()


def _skills_inventory(codex: Path, cwd: Path, timeout: float) -> dict[str, Any]:
    try:
        process = subprocess.Popen(
            [str(codex), "app-server", "--listen", "stdio://"],
            cwd=cwd,
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            bufsize=1,
        )
    except OSError as exc:
        raise ProfileError(f"cannot start Codex app-server: {exc}") from exc
    try:
        if process.stdin is None:
            raise ProfileError("Codex app-server stdin is unavailable")
        _write_message(
            process.stdin,
            {
                "id": 1,
                "method": "initialize",
                "params": {
                    "clientInfo": {
                        "name": "documents-codex-profile",
                        "version": "1.0",
                    }
                },
            },
        )
        _read_response(process, 1, timeout)
        _write_message(process.stdin, {"method": "initialized", "params": {}})
        _write_message(
            process.stdin,
            {
                "id": 2,
                "method": "skills/list",
                "params": {"cwds": [str(cwd)], "forceReload": True},
            },
        )
        return _read_response(process, 2, timeout)
    finally:
        if process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=2)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=2)


def _is_relative_to_root(path_value: str, roots: tuple[Path, ...]) -> bool:
    path = Path(path_value).expanduser()
    candidates = (path.absolute(), path.resolve(strict=False))
    for root in roots:
        root_candidates = (root.absolute(), root.resolve(strict=False))
        if any(
            candidate.is_relative_to(root_candidate)
            for candidate in candidates
            for root_candidate in root_candidates
        ):
            return True
    return False


def _user_skill_paths(
    payload: dict[str, Any], roots: tuple[Path, ...]
) -> tuple[str, ...]:
    data = payload.get("data")
    if not isinstance(data, list) or len(data) != 1 or not isinstance(data[0], dict):
        raise ProfileError("Codex skills inventory must contain exactly one cwd entry")
    entry = data[0]
    skills = entry.get("skills")
    errors = entry.get("errors")
    if not isinstance(skills, list) or not isinstance(errors, list):
        raise ProfileError("Codex skills inventory is malformed")
    paths: set[str] = set()
    for item in skills:
        if not isinstance(item, dict) or not isinstance(item.get("path"), str):
            raise ProfileError("Codex skills inventory contains an invalid entry")
        if item.get("scope") != "user":
            continue
        path = item["path"]
        if _is_relative_to_root(path, roots):
            paths.add(path)
    for item in errors:
        if not isinstance(item, dict) or not isinstance(item.get("path"), str):
            raise ProfileError("Codex skills inventory contains an invalid entry")
        path = item["path"]
        if _is_relative_to_root(path, roots):
            paths.add(path)
    return tuple(sorted(paths))


def inventory(
    codex: Path,
    contract: ProfileContract,
    cwd: Path,
    user_skill_roots: tuple[Path, ...],
    timeout: float,
) -> CodexInventory:
    servers = _mcp_inventory(codex, timeout)
    if contract.server not in servers:
        raise ProfileError(f"required Codex MCP server is missing: {contract.server}")
    skill_payload = _skills_inventory(codex, cwd, timeout)
    return CodexInventory(
        mcp_servers=servers,
        disabled_skill_paths=_user_skill_paths(skill_payload, user_skill_roots),
    )


def _toml_key(value: str) -> str:
    return value if _BARE_TOML_KEY.fullmatch(value) else json.dumps(value)


def _toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render_profile(contract: ProfileContract, current: CodexInventory) -> str:
    lines = [
        _GENERATED_MARKER,
        "# Re-run the generator when Codex MCP or user Skill inventory changes.",
        "",
    ]
    for server in current.mcp_servers:
        lines.append(f"[mcp_servers.{_toml_key(server)}]")
        if server == contract.server:
            tools = ", ".join(_toml_string(item) for item in contract.allowed_tools)
            lines.extend(
                (
                    "enabled = true",
                    "required = true",
                    f"default_tools_approval_mode = {_toml_string(contract.approval_mode)}",
                    f"enabled_tools = [{tools}]",
                )
            )
        else:
            lines.append("enabled = false")
        lines.append("")
    for skill_path in current.disabled_skill_paths:
        lines.extend(
            (
                "[[skills.config]]",
                f"path = {_toml_string(skill_path)}",
                "enabled = false",
                "",
            )
        )
    return "\n".join(lines)


def _report(
    ok: bool, profile_path: Path, current: CodexInventory, errors: list[str]
) -> None:
    print(
        json.dumps(
            {
                "ok": ok,
                "profile_path": str(profile_path),
                "mcp_server_count": len(current.mcp_servers),
                "disabled_user_skill_count": len(current.disabled_skill_paths),
                "errors": errors,
            },
            ensure_ascii=False,
        )
    )


def _install(profile_path: Path, expected: str, current: CodexInventory) -> int:
    if os.path.lexists(profile_path):
        try:
            existing_stat = profile_path.lstat()
        except OSError as exc:
            _report(False, profile_path, current, [f"profile unavailable: {exc}"])
            return 1
        if not stat.S_ISREG(existing_stat.st_mode):
            _report(
                False,
                profile_path,
                current,
                [
                    f"profile must be a regular file owned by the generator: {profile_path}"
                ],
            )
            return 1
        try:
            existing = profile_path.read_text(encoding="utf-8")
        except (OSError, UnicodeError):
            existing = None
        if existing == expected and stat.S_IMODE(existing_stat.st_mode) == 0o600:
            _report(True, profile_path, current, [])
            return 0
        if existing is None or not existing.startswith(_GENERATED_MARKER + "\n"):
            _report(
                False,
                profile_path,
                current,
                [f"profile already exists with different content: {profile_path}"],
            )
            return 1

    profile_path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(
        prefix=f".{profile_path.name}.", dir=profile_path.parent
    )
    temporary_path = Path(temporary)
    try:
        os.fchmod(descriptor, 0o600)
        with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
            descriptor = -1
            stream.write(expected)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary_path, profile_path)
    except OSError as exc:
        _report(False, profile_path, current, [f"cannot install profile: {exc}"])
        return 1
    finally:
        if descriptor >= 0:
            os.close(descriptor)
        if temporary_path.exists():
            temporary_path.unlink()
    _report(True, profile_path, current, [])
    return 0


def _check(profile_path: Path, expected: str, current: CodexInventory) -> int:
    if not os.path.lexists(profile_path):
        errors = [f"profile missing: {profile_path}"]
    elif profile_path.is_symlink() or not profile_path.is_file():
        errors = [f"profile must be a regular file: {profile_path}"]
    else:
        try:
            actual = profile_path.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as exc:
            errors = [f"profile unavailable: {exc}"]
        else:
            errors = [] if actual == expected else [f"profile drift: {profile_path}"]
    _report(not errors, profile_path, current, errors)
    return 0 if not errors else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("render", "install", "check"))
    parser.add_argument("--project-registry", type=Path, default=DEFAULT_REGISTRY)
    parser.add_argument("--codex-bin")
    parser.add_argument("--cwd", type=Path, default=ROOT)
    parser.add_argument("--profile-path", type=Path, default=DEFAULT_PROFILE)
    parser.add_argument("--user-skill-root", action="append", type=Path)
    parser.add_argument("--timeout", type=float, default=10.0)
    args = parser.parse_args(argv)

    roots = tuple(args.user_skill_root or ()) or (
        Path.home() / ".agents" / "skills",
        Path.home() / ".codex" / "skills",
    )
    try:
        contract = _load_contract(args.project_registry)
        codex = _codex_binary(args.codex_bin)
        current = inventory(codex, contract, args.cwd, roots, args.timeout)
        expected = render_profile(contract, current)
    except ProfileError as exc:
        print(json.dumps({"ok": False, "errors": [str(exc)]}, ensure_ascii=False))
        return 1

    if args.command == "render":
        print(expected, end="")
        return 0
    if args.command == "install":
        return _install(args.profile_path, expected, current)
    return _check(args.profile_path, expected, current)


if __name__ == "__main__":
    raise SystemExit(main())
