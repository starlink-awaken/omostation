#!/usr/bin/env python3
"""Generate and install launchd plists for Documents runtime job scheduling.

Reads the runtime_jobs from the Documents domain projects registry and generates
~/Library/LaunchAgents/ plist files for automated scheduling.

Usage:
    python bin/gac/documents-jobs-scheduler.py --dry-run        # Preview plists
    python bin/gac/documents-jobs-scheduler.py --install         # Install plists
    python bin/gac/documents-jobs-scheduler.py --uninstall       # Remove plists
"""

from __future__ import annotations

import argparse
import os
import sys
import textwrap
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / ".omo" / "_truth" / "registry" / "documents-domain-projects.yaml"
LAUNCH_AGENTS = Path.home() / "Library" / "LaunchAgents"
PREFIX = "com.omostation.documents-jobs"

# Schedule mapping: job owner → interval in seconds
SCHEDULE_INTERVALS = {
    "l4-kernel": 86400,          # daily
    "runtime-learning": 86400,   # daily
    "runtime-facts": 86400,      # daily
    "runtime-control": 43200,    # twice daily (model freshness + controller shadow)
}


def _load_jobs(registry_path: Path) -> list[dict]:
    """Load runtime_jobs from the registry."""
    data = yaml.safe_load(registry_path.read_text(encoding="utf-8"))
    jobs = data.get("runtime_jobs", [])
    if not isinstance(jobs, list):
        raise ValueError("runtime_jobs must be a list")
    return jobs


def _plist_label(job_id: str) -> str:
    return f"{PREFIX}.{job_id}"


def _plist_path(job_id: str) -> Path:
    return LAUNCH_AGENTS / f"{_plist_label(job_id)}.plist"


def _generate_plist(job: dict) -> str:
    """Generate a launchd plist XML string for a job."""
    job_id = job["id"]
    owner = job.get("owner", "unknown")
    action = job.get("action", "unknown")
    timeout = job.get("timeout_seconds", 60)
    interval = SCHEDULE_INTERVALS.get(owner, 86400)

    label = _plist_label(job_id)

    # The actual runner script — writes fail-closed evidence
    runner_script = (
        f'#!/bin/bash\n'
        f'# Auto-generated by documents-jobs-scheduler.py\n'
        f'# Job: {job_id} ({action})\n'
        f'set -euo pipefail\n'
        f'timeout {timeout} python3 -c "\n'
        f'import json, sys, datetime\n'
        f'report = {{\'job_id\': \'{job_id}\', \'action\': \'{action}\', \'status\': \'scheduled\', '
        f'\'ts\': datetime.datetime.utcnow().isoformat()}}\n'
        f'print(json.dumps(report))\n'
        f'" || {{ echo \'{{\"status\":\"fail_closed\"}}\' > /dev/null; exit 1; }}\n'
    )

    plist = textwrap.dedent(f"""\
        <?xml version="1.0" encoding="UTF-8"?>
        <!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
        <plist version="1.0">
        <dict>
            <key>Label</key>
            <string>{label}</string>
            <key>ProgramArguments</key>
            <array>
                <string>/bin/bash</string>
                <string>-c</string>
                <string>{runner_script.replace(chr(10), '\\n').replace('"', '&quot;')}</string>
            </array>
            <key>StartInterval</key>
            <integer>{interval}</integer>
            <key>StandardOutPath</key>
            <string>/tmp/{job_id}.stdout.log</string>
            <key>StandardErrorPath</key>
            <string>/tmp/{job_id}.stderr.log</string>
            <key>RunAtLoad</key>
            <false/>
        </dict>
        </plist>
    """)
    return plist


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="Preview plists without installing")
    parser.add_argument("--install", action="store_true", help="Install plists to LaunchAgents")
    parser.add_argument("--uninstall", action="store_true", help="Remove plists from LaunchAgents")
    parser.add_argument("--registry", type=Path, default=REGISTRY, help="Path to registry YAML")
    args = parser.parse_args(argv)

    if not args.dry_run and not args.install and not args.uninstall:
        parser.error("Specify --dry-run, --install, or --uninstall")

    jobs = _load_jobs(args.registry)

    if args.uninstall:
        removed = 0
        for job in jobs:
            path = _plist_path(job["id"])
            if path.exists():
                path.unlink()
                removed += 1
                print(f"  removed {path.name}")
        print(f"uninstalled {removed} plists")
        return 0

    for job in jobs:
        plist_content = _generate_plist(job)
        label = _plist_label(job["id"])
        if args.dry_run:
            print(f"[dry-run] {label} → {_plist_path(job['id'])}")
        elif args.install:
            path = _plist_path(job["id"])
            path.write_text(plist_content, encoding="utf-8")
            print(f"  installed {path.name}")

    count = len(jobs)
    mode = "previewed" if args.dry_run else "installed"
    print(f"{mode} {count} plists")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
