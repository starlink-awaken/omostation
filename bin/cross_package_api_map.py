"""Cross-package API map generator.

Joins the Agora BOS registry (`projects/agora/etc/bos-services.yaml`)
with the Kairon workspace members (`projects/kairon/pyproject.toml`)
to produce a single `docs/overview/cross-package-api-map.md` table
that consumers (cockpit, runtime, c2g) can read to discover which
Kairon package backs which external mesh route.

Usage:
    python3 bin/cross-package-api-map.py
        --bos-registry projects/agora/etc/bos-services.yaml
        --kairon-root projects/kairon
        --out docs/overview/cross-package-api-map.md
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

import yaml


# Match the python module a command runs against. We look for a
# `python -m <package>.<module>` substring or a direct `<package>`
# script invocation. This is intentionally narrow so it does not
# over-claim on bare `uv run` invocations.
PYTHON_DASH_M_RE = re.compile(r"python\d?(?:\s+-[A-Za-z]+\s+\S+)*\s+-m\s+(?P<module>[\w.]+)")


def _kairon_workspace_members(kairon_root: Path) -> set[str]:
    """Return the set of Kairon package names declared as workspace
    members via the `[tool.uv.workspace] members = ["packages/*"]` glob
    plus any explicit `[tool.uv.sources]` overrides."""
    pyproject = kairon_root / "pyproject.toml"
    text = pyproject.read_text(encoding="utf-8")
    members: set[str] = set()
    # Match the simple packages/* glob.
    if 'members = ["packages/*"]' in text:
        for child in (kairon_root / "packages").iterdir():
            if (child / "pyproject.toml").exists():
                members.add(child.name)
    # Add explicit [tool.uv.sources] workspace members.
    for match in re.finditer(r"^\s*([\w-]+)\s*=\s*\{\s*workspace\s*=\s*true\s*\}", text, re.MULTILINE):
        members.add(match.group(1))
    return members


def _module_to_package(module: str, workspace: set[str]) -> str | None:
    """Map `ontoderive.mcp_server` to its workspace member `ontoderive`."""
    for member in workspace:
        if module == member or module.startswith(member + "."):
            return member
    return None


def _services_with_kairon_backend(
    bos_registry: Path, workspace: set[str]
) -> list[dict[str, Any]]:
    docs = [d for d in yaml.safe_load_all(bos_registry.read_text(encoding="utf-8")) if d]
    services: list[dict[str, Any]] = []
    for d in docs:
        services.extend(d.get("services", []))
    annotated: list[dict[str, Any]] = []
    for s in services:
        record = dict(s)
        cmd = s.get("command") or []
        cmd_str = " ".join(cmd) if isinstance(cmd, list) else str(cmd)
        match = PYTHON_DASH_M_RE.search(cmd_str)
        kairon_pkg: str | None = None
        module = None
        if match:
            module = match.group("module")
            kairon_pkg = _module_to_package(module, workspace)
        record["_kairon_pkg"] = kairon_pkg
        record["_python_module"] = module
        annotated.append(record)
    return annotated


def _build_markdown(annotated: list[dict[str, Any]], workspace: set[str]) -> str:
    by_kairon: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for s in annotated:
        if s["_kairon_pkg"]:
            by_kairon[s["_kairon_pkg"]].append(s)
    lines: list[str] = []
    lines.append("# Cross-Package API Map")
    lines.append("")
    lines.append("Generated by `bin/cross-package-api-map.py`.")
    lines.append("")
    lines.append("Auto-joins the Agora BOS registry against the Kairon")
    lines.append("workspace members so consumers can discover which")
    lines.append("Kairon package backs each external mesh route.")
    lines.append("")
    lines.append(f"- Kairon workspace members: {len(workspace)}")
    lines.append(f"- BOS services inspected: {len(annotated)}")
    lines.append(f"- Routes with a Kairon backend: {sum(len(v) for v in by_kairon.values())}")
    lines.append("")
    lines.append("## Kairon package ↔ BOS URI map")
    lines.append("")
    lines.append("| Kairon package | Python module | BOS URI | Domain | Action | Transport | Status |")
    lines.append("|---|---|---|---|---|---|---|")
    for kairon_pkg in sorted(by_kairon):
        for s in sorted(by_kairon[kairon_pkg], key=lambda x: x.get("uri", "")):
            lines.append(
                f"| {kairon_pkg} | `{s.get('_python_module') or ''}` | "
                f"`{s.get('uri', '')}` | {s.get('domain', '')} | {s.get('action', '')} | "
                f"{s.get('transport', '')} | {s.get('status', 'active')} |"
            )
    lines.append("")
    lines.append("## Kairon packages without any BOS route")
    lines.append("")
    with_route = set(by_kairon)
    without_route = sorted(workspace - with_route)
    if without_route:
        for pkg in without_route:
            lines.append(f"- `{pkg}`")
    else:
        lines.append("- (none — every workspace member has at least one BOS route)")
    lines.append("")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--bos-registry",
        type=Path,
        default=Path("projects/agora/etc/bos-services.yaml"),
    )
    parser.add_argument(
        "--kairon-root",
        type=Path,
        default=Path("projects/kairon"),
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("docs/overview/cross-package-api-map.md"),
    )
    args = parser.parse_args(argv)

    if not args.bos_registry.exists():
        print(f"bos registry not found: {args.bos_registry}", file=sys.stderr)
        return 1
    if not args.kairon_root.exists():
        print(f"kairon root not found: {args.kairon_root}", file=sys.stderr)
        return 1

    workspace = _kairon_workspace_members(args.kairon_root)
    annotated = _services_with_kairon_backend(args.bos_registry, workspace)
    md = _build_markdown(annotated, workspace)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(md, encoding="utf-8")
    print(
        f"wrote {args.out} "
        f"({sum(1 for s in annotated if s['_kairon_pkg'])}/{len(annotated)} routes mapped)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
