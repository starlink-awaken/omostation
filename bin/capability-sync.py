#!/usr/bin/env python3
"""
Capability Registry Generator — PR-B 四源扫描生成器

扫描四个来源的能力：
1. ~/.claude/skills/*/SKILL.md — 全局 skills
2. <workspace>/.agents/skills/*/SKILL.md — 项目 skills
3. orca skills list --json — Orca skills
4. ~/.claude.json mcpServers — MCP servers

生成 docs/generated/capability-registry.yaml

用法:
    python bin/capability-sync.py sync      # 扫描并生成 registry
    python bin/capability-sync.py check      # 检查反漂移（exit 1 if drift）
    python bin/capability-sync.py find --query <query>  # 模糊查找
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from typing import Final

# ── 常量 ─────────────────────────────────────────────────────────────────────────
GENERATED_HEADER: Final = """# GENERATED — 勿手编, make capability-sync 刷新
# This file is auto-generated by bin/capability-sync.py
# Source: claude-global skills + project agents skills + orca skills + MCP servers
# Last sync: {timestamp}
"""

MAX_DESC_LEN: Final = 120

# ── 类型定义 ─────────────────────────────────────────────────────────────────────
class Capability:
    """能力条目"""

    __slots__ = ("id", "source", "name", "description", "invoke")

    def __init__(
        self,
        *,
        source: str,
        name: str,
        description: str,
        invoke: str,
    ) -> None:
        self.id = f"{source}:{name.lower().replace(' ', '-')}"
        self.source = source  # claude-global | project-agents | orca | mcp
        self.name = name
        self.description = self._truncate(description)
        self.invoke = invoke

    def _truncate(self, text: str) -> str:
        """截断过长的描述"""
        if len(text) <= MAX_DESC_LEN:
            return text
        return text[: MAX_DESC_LEN - 3] + "..."

    def as_dict(self) -> dict:
        """转换为字典"""
        return {
            "id": self.id,
            "source": self.source,
            "name": self.name,
            "description": self.description,
            "invoke": self.invoke,
        }


# ── 扫描函数 ─────────────────────────────────────────────────────────────────────

def scan_skill_frontmatter(skill_dir: Path, source_prefix: str) -> list[Capability]:
    """
    扫描 SKILL.md frontmatter

    Args:
        skill_dir: skills 根目录
        source_prefix: claude-global 或 project-agents
    """
    capabilities: list[Capability] = []

    if not skill_dir.exists():
        return capabilities

    for skill_path in skill_dir.glob("*/SKILL.md"):
        try:
            content = skill_path.read_text(encoding="utf-8")
            lines = content.split("\n")

            # 找 frontmatter 块（--- 包裹）
            if not lines[0].strip() == "---":
                continue

            frontmatter_lines: list[str] = []
            for line in lines[1:]:
                if line.strip() == "---":
                    break
                frontmatter_lines.append(line)

            # 解析 frontmatter（简单 key: value）
            frontmatter = {}
            for line in frontmatter_lines:
                if ":" in line:
                    key, value = line.split(":", 1)
                    # 规范化：去掉外层引号（如果有的话），但保留内层转义
                    frontmatter[key.strip()] = value.strip().strip('"')

            name = frontmatter.get("name", "")
            description = frontmatter.get("description", "")

            if not name:
                continue

            capabilities.append(
                Capability(
                    source=source_prefix,
                    name=name,
                    description=description,
                    invoke=f"Skill 工具 /{name}",
                )
            )
        except (OSError, UnicodeDecodeError):
            # 跳过读不了的文件
            continue

    return capabilities


def scan_orca_skills() -> list[Capability]:
    """
    扫描 orca skills list --json

    优雅降级：orca 不可达时返回空列表 + warning
    """
    capabilities: list[Capability] = []

    try:
        result = subprocess.run(
            ["orca", "skills", "list", "--json"],
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        )

        if result.returncode != 0:
            print("[WARN] orca skills list 失败，跳过 orca 源", file=sys.stderr)
            return capabilities

        data = json.loads(result.stdout)
        topics = data.get("topics", [])

        for topic in topics:
            name = topic.get("name", "")
            description = topic.get("description", "")

            if not name:
                continue

            capabilities.append(
                Capability(
                    source="orca",
                    name=name,
                    description=description,
                    invoke="orca skills get <name>",
                )
            )
    except (subprocess.TimeoutExpired, json.JSONDecodeError, FileNotFoundError, OSError):
        print("[WARN] orca 不可达，跳过 orca 源", file=sys.stderr)
        return capabilities

    return capabilities


def scan_mcp_servers(claude_json_path: Path) -> list[Capability]:
    """
    扫描 ~/.claude.json 的 mcpServers 键

    只取 server 名列表，不读详细配置
    """
    capabilities: list[Capability] = []

    if not claude_json_path.exists():
        return capabilities

    try:
        content = claude_json_path.read_text(encoding="utf-8")
        data = json.loads(content)
        mcp_servers = data.get("mcpServers", {})

        for server_name in mcp_servers.keys():
            capabilities.append(
                Capability(
                    source="mcp",
                    name=server_name,
                    description=f"MCP server: {server_name}",
                    invoke="MCP server (需在 mcp 配置)",
                )
            )
    except (OSError, json.JSONDecodeError, UnicodeDecodeError):
        # 跳过读不了的配置
        pass

    return capabilities


# ── 主流程 ───────────────────────────────────────────────────────────────────────

def scan_all_sources(workspace_root: Path) -> list[Capability]:
    """
    扫描四个源并合并

    Args:
        workspace_root: 工作区根目录
    """
    all_capabilities: list[Capability] = []

    # 源1: 全局 skills
    global_skills = Path.home() / ".claude" / "skills"
    all_capabilities.extend(scan_skill_frontmatter(global_skills, "claude-global"))

    # 源2: 项目 skills
    project_skills = workspace_root / ".agents" / "skills"
    all_capabilities.extend(scan_skill_frontmatter(project_skills, "project-agents"))

    # 源3: orca skills
    all_capabilities.extend(scan_orca_skills())

    # 源4: MCP servers
    claude_json = Path.home() / ".claude.json"
    all_capabilities.extend(scan_mcp_servers(claude_json))

    # 按 source + name 去重（后面的覆盖前面的）
    seen: dict[str, Capability] = {}
    for cap in all_capabilities:
        key = f"{cap.source}:{cap.name.lower()}"
        seen[key] = cap

    return list(seen.values())


def generate_registry(capabilities: list[Capability], output_path: Path) -> None:
    """
    生成 capability-registry.yaml
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)

    timestamp = datetime.now(timezone.utc).isoformat()
    header = GENERATED_HEADER.format(timestamp=timestamp)

    lines = [header, "generated_at:", f'  "{timestamp}"', "generator:", "  capability-sync/v1", "capabilities:"]

    for cap in sorted(capabilities, key=lambda c: (c.source, c.name.lower())):
        lines.append(f'  - id: "{cap.id}"')
        lines.append(f"    source: {cap.source}")
        lines.append(f'    name: "{cap.name}"')
        lines.append(f'    description: "{cap.description}"')
        lines.append(f'    invoke: "{cap.invoke}"')

    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def load_registry(path: Path) -> list[Capability]:
    """加载现有 registry"""
    if not path.exists():
        return []

    capabilities: list[Capability] = []
    content = path.read_text(encoding="utf-8")

    # 跳过 header
    lines = [line for line in content.split("\n") if not line.startswith("#")]
    yaml_text = "\n".join(lines)

    # 简单解析（只读我们写的格式）
    current_cap: dict[str, str] | None = None
    for line in yaml_text.split("\n"):
        line = line.rstrip()
        if not line or line.startswith(("generated_at:", "generator:", "capabilities:")):
            continue

        if line.startswith("  - id:"):
            if current_cap:
                capabilities.append(
                    Capability(
                        source=current_cap["source"],
                        name=current_cap["name"],
                        description=current_cap["description"],
                        invoke=current_cap["invoke"],
                    )
                )
            current_cap = {"id": line.split(":", 1)[1].strip().strip('"')}
        elif current_cap and ": " in line:
            key, value = line.split(":", 1)
            # 规范化：去掉外层引号
            current_cap[key.strip()] = value.strip().strip('"')

    # 最后一个
    if current_cap:
        capabilities.append(
            Capability(
                source=current_cap["source"],
                name=current_cap["name"],
                description=current_cap["description"],
                invoke=current_cap["invoke"],
            )
        )

    return capabilities


def check_drift(existing: list[Capability], current: list[Capability]) -> bool:
    """
    检查漂移

    Returns:
        True if drifted (有差异)
    """
    existing_set = {f"{c.source}:{c.name.lower()}" for c in existing}
    current_set = {f"{c.source}:{c.name.lower()}" for c in current}

    if existing_set != current_set:
        return True

    # 检查内容变化
    existing_dict = {f"{c.source}:{c.name.lower()}": c for c in existing}
    for cap in current:
        key = f"{cap.source}:{cap.name.lower()}"
        if key in existing_dict:
            existing_cap = existing_dict[key]
            if (
                cap.description != existing_cap.description
                or cap.invoke != existing_cap.invoke
            ):
                return True

    return False


def find_capabilities(capabilities: list[Capability], query: str) -> list[Capability]:
    """
    模糊查找（name/description 子串，大小写不敏感）
    """
    query_lower = query.lower()
    return [
        c
        for c in capabilities
        if query_lower in c.name.lower() or query_lower in c.description.lower()
    ]


# ── CLI 入口 ─────────────────────────────────────────────────────────────────────

def main() -> int:
    parser = argparse.ArgumentParser(description="Capability Registry Generator")
    subparsers = parser.add_subparsers(dest="command", required=True)

    # sync 子命令
    sync_parser = subparsers.add_parser("sync", help="扫描四源并生成 registry")
    sync_parser.add_argument(
        "--workspace-root",
        type=Path,
        default=Path(__file__).parents[1],
        help="工作区根目录",
    )
    sync_parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).parents[1] / "docs" / "generated" / "capability-registry.yaml",
        help="输出文件路径",
    )

    # check 子命令
    check_parser = subparsers.add_parser("check", help="检查反漂移")
    check_parser.add_argument(
        "--workspace-root",
        type=Path,
        default=Path(__file__).parents[1],
        help="工作区根目录",
    )
    check_parser.add_argument(
        "--registry",
        type=Path,
        default=Path(__file__).parents[1] / "docs" / "generated" / "capability-registry.yaml",
        help="现有 registry 路径",
    )

    # find 子命令
    find_parser = subparsers.add_parser("find", help="模糊查找 capability")
    find_parser.add_argument("--query", required=True, help="查询字符串")
    find_parser.add_argument(
        "--registry",
        type=Path,
        default=Path(__file__).parents[1] / "docs" / "generated" / "capability-registry.yaml",
        help="registry 路径",
    )

    args = parser.parse_args()

    if args.command == "sync":
        capabilities = scan_all_sources(args.workspace_root)
        generate_registry(capabilities, args.output)
        print(f"✅ 已生成 {len(capabilities)} 条 capability 到 {args.output}")
        return 0

    elif args.command == "check":
        existing = load_registry(args.registry)
        current = scan_all_sources(args.workspace_root)

        if check_drift(existing, current):
            print("❌ 检测到 capability registry 漂移，请运行 make capability-sync 修复", file=sys.stderr)
            return 1
        else:
            print("✅ capability registry 无漂移")
            return 0

    elif args.command == "find":
        capabilities = load_registry(args.registry)
        results = find_capabilities(capabilities, args.query)

        if not results:
            print(f"未找到匹配 '{args.query}' 的 capability")
            return 1

        print(f"找到 {len(results)} 条匹配 capability:\n")
        for cap in results:
            print(f"  [{cap.source}] {cap.name}")
            print(f"    {cap.description}")
            print(f"    调用: {cap.invoke}\n")
        return 0

    return 1


if __name__ == "__main__":
    sys.exit(main())
