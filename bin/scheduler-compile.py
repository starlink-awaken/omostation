#!/usr/bin/env python3
"""scheduler-compile.py — 调度编译器 v1: 登记源 → 编译三格式产出 (ADR-A 生成模式).

从 .omo/cron/registry.yaml 单一登记源编译:
  --format crontab   输出标准 crontab 格式行
  --format launchd   输出 launchd plist 骨架
  --format github    输出 GitHub Actions schedule YAML 片段

用法:
  python3 bin/scheduler-compile.py --check     # 校验登记↔安装一致性
  python3 bin/scheduler-compile.py --generate crontab > output.txt
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "bin" / "lib"))
from cron_normalize import current_host as _current_host  # noqa: E402
from cron_normalize import active_crontab_jobs as _active_crontab_jobs  # noqa: E402
from cron_normalize import active_plane_jobs as _active_plane_jobs  # noqa: E402
from cron_normalize import expand_workspace as _expand_workspace  # noqa: E402
from cron_normalize import host_scoped_jobs as _host_scoped  # noqa: E402
from cron_normalize import normalize_installed_line as _normalize_installed_line  # noqa: E402
from cron_normalize import normalize_interpreter as _normalize_interpreter  # noqa: E402
from cron_normalize import pick_interpreter as _pick_interpreter  # noqa: E402
from cron_normalize import resolve_python_command as _resolve_python_command  # noqa: E402
from cron_normalize import (  # noqa: E402
    unfoldable_interpreter_jobs as _unfoldable_interpreter_jobs,
)

WORKSPACE = Path(__file__).resolve().parents[1]
REGISTRY = WORKSPACE / ".omo" / "cron" / "registry.yaml"


def _load_raw() -> dict:
    import yaml
    if not REGISTRY.exists():
        return {}
    docs = [d for d in yaml.safe_load_all(REGISTRY.read_text()) if d]
    return docs[-1] if docs else {}


def _load_jobs() -> list[dict]:
    return _load_raw().get("jobs", [])


def compile_crontab(jobs: list[dict], *, resolve: bool = True) -> list[str]:
    """只输出 status=active 且 planes 含 crontab 的条目 (v2 平面过滤).

    历史 bug: 不过滤 planes 会把 launchd-only 的 always 条目混进 crontab
    产物, 整文件安装会因非法 schedule 被 cron 拒绝 (2026-09-19 实证).
    与 check_drift 的登记侧过滤保持一致.

    主机维度过滤 (`hosts`) 与 check_drift 同口径 —— 否则 `--generate` 会产出
    本机不该装的条目, `--diff` 会把它报成「待新增」。

    `resolve=True` (默认): 把登记面的裸 `python3` 按**本机**换成可证可用的绝对
    解释器 (CRON-BARE-PYTHON3-PY39-IMPORT-DEATH 选项 ③)。登记面保持宿主中性,
    宿主差异在这一处收口; 解析不出安全解释器时原样输出, 不制造新失败形态。
    与 `check_drift` 不冲突: 比对键 `normalize_interpreter` 会把绝对路径折回裸
    `python3`, 所以替换不算 drift —— 前提是候选 basename 是 `python3[.N]`
    (由 `cron_normalize.interpreter_candidates` 强制)。
    """
    out = ["# Generated by scheduler-compile.py — DO NOT EDIT MANUALLY"]
    for j in _active_crontab_jobs(jobs):
        sched = j.get("schedule", "")
        cmd = j.get("command", "")
        if resolve:
            cmd, _reason = _resolve_python_command(cmd)
        # command 已含完整 cd 与日志重定向 (registry.yaml v2 范式),
        # 编译器只加 schedule, 不再包 cd / log 避免嵌套。
        out.append(f"{sched} {cmd}")
    return out


def compile_launchd(jobs: list[dict], *, resolve: bool = True) -> dict:
    """编译 launchd plist 骨架 —— 与 crontab 路径同一套过滤口径.

    此前本函数**只过滤 planes**, 不过 `status` 也不过 `hosts` ⇒ 实测把 6 条
    `proposed` 条目 (resident-launchd-sediment/monitor/heartbeat、
    knowledge-foundry-6h、panorama-dashboard、panorama-refresh-guard) 也编译进产物,
    而 `--generate crontab` 会排除它们。同一份登记面在两个平面上给出不同的活跃集。

    解释器此前写死 `/usr/bin/python3` —— 那正是 3.9 (Xcode) 路径, 与 crontab 平面
    踩的是同一个 `ImportError: cannot import name 'UTC'` 根因; 现按本机解析,
    不可判定时退回原写死值 (不改变既有形态)。
    `ProgramArguments[1]` 传的是整条 shell 命令而非脚本路径, 是另一个已知缺陷,
    本次不动它 (骨架无消费方, 改形需要单独授权)。
    """
    agents = {}
    for j in _active_plane_jobs(jobs, "launchd"):
        if "launchd" not in j.get("planes", []):
            continue
        label = f"com.omostation.{j['name']}"
        python = (_pick_interpreter(j.get("command", "")) or "/usr/bin/python3") if resolve else "/usr/bin/python3"
        agents[label] = {
            "Label": label,
            "ProgramArguments": [python, j["command"]],
            "RunAtLoad": False,
        }
    return agents


def compile_github(jobs: list[dict]) -> str:
    lines = ["on:", "  schedule:"]
    seen_crons = set()
    for j in jobs:
        cron_expr = j.get("schedule", "")
        if cron_expr and cron_expr not in seen_crons:
            lines.append(f"    - cron: '{cron_expr}'")
            seen_crons.add(cron_expr)
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description="调度编译器 v1")
    ap.add_argument("--check", action="store_true", help="校验登记↔安装一致性")
    ap.add_argument("--generate", choices=["crontab", "launchd"], help="生成指定格式")
    ap.add_argument("--diff", action="store_true", help="只读: 候选 crontab vs 已装 crontab 的差异 (装机前看会删/会加什么)")
    ap.add_argument(
        "--no-resolve-interpreter",
        action="store_true",
        help="生成时保留登记面的裸 python3 (默认按本机解析成可证可用的绝对解释器)",
    )
    args = ap.parse_args()
    jobs = _load_jobs()

    if args.diff:
        print(json.dumps(diff_installation(), ensure_ascii=False, indent=2))
        return 0
    resolve = not args.no_resolve_interpreter
    if args.generate == "crontab":
        print("\n".join(compile_crontab(jobs, resolve=resolve)))
        return 0
    if args.generate == "launchd":
        print(json.dumps(compile_launchd(jobs, resolve=resolve), indent=2))
        return 0

    result = check_drift() if hasattr(sys.modules[__name__], 'check_drift') else {"ok": True}
    print(json.dumps(result, ensure_ascii=False))
    return 0 if result.get("ok", True) else 1


def _launchd_prefixes():
    return ("com.omostation.", "com.opencode.", "com.l4.", "com.aetherforge.", "com.omlxc.")


def check_launchd_plane(registered):
    """T16-01 shadow: launchd 平面三项检查, **只报告, 不参与 ok 判定**.

    C1 登记↔安装 label 双向差集; C2 plistlib 可解析性 (不以 plutil 为准);
    C3 ProgramArguments 目标是否存在.

    label 合成现状: 18 条 launchd 登记中仅 7 条能由 `com.omostation.{name}` 命中,
    其余用其他 label 方案且**无显式 label 字段**。故本阶段 label 匹配一律标记为
    heuristic, 只作存量盘点用, 不作为漂移判据 (ADR-0457 三段式: shadow 不阻断)。
    """
    import plistlib
    from pathlib import Path

    home = Path.home()
    la = home / "Library" / "LaunchAgents"
    reg_labels, unparseable, dead_targets, installed = set(), [], [], set()
    try:
        installed_labels = {p.stem for p in la.glob("com.*.plist")} if la.is_dir() else set()
    except Exception:
        installed_labels = set()

    for pref in _launchd_prefixes():
        for pf in sorted(la.glob(pref + "*.plist")) if la.is_dir() else []:
            try:
                data = plistlib.loads(pf.read_bytes())
            except Exception as exc:  # noqa: BLE001 — C2: 不可解析须可见而非静默
                unparseable.append({"file": pf.name, "error": type(exc).__name__})
                continue
            label = str(data.get("Label") or pf.stem)
            installed.add(label)
            for tok in data.get("ProgramArguments") or []:
                if not isinstance(tok, str) or not tok.startswith("/"):
                    continue
                if not (tok.endswith((".py", ".sh")) or "/bin/" in tok):
                    continue
                if not Path(tok).exists():
                    dead_targets.append({"label": label, "target": tok})
                break

    reg_entries = [
        j for j in registered
        if j.get("status", "active") == "active" and "launchd" in (j.get("planes") or [])
    ]
    for j in reg_entries:
        explicit = j.get("label")
        reg_labels.add(str(explicit) if explicit else f"com.omostation.{j['name']}")
    matched = {lbl for lbl in reg_labels if lbl in installed}
    missing_installed = sorted(reg_labels - installed)
    undeclared_installed = sorted(installed - reg_labels)

    return {
        "mode": "shadow",
        "blocks_gate": False,
        "registered_count": len(reg_entries),
        "installed_count": len(installed),
        "missing_installed_count": len(missing_installed),
        "missing_installed": missing_installed,
        "undeclared_installed_count": len(undeclared_installed),
        "undeclared_installed_sample": undeclared_installed[:15],
        "label_match": {
            "matched": len(matched),
            "registered": len(reg_labels),
            "rate": round(len(matched) / len(reg_labels), 3) if reg_labels else None,
            "note": "label 取显式 label 字段, 缺省才合成 com.omostation.{name}。"
                    "2026-09-29 已为全部 17 条登记补齐显式 label, 命中率 17/17 —— "
                    "这是本项升 warning 的前置条件 (ADR-0457 阶段门)。",
        },
        "unparseable_plists": unparseable,
        "dead_targets": dead_targets,
    }




def diff_installation(installed_lines: list[str] | None = None) -> dict:
    """只读: 候选 crontab (注册表编译产物) vs 已装 crontab 的差异。

    背景 (2026-11-07 实测): `.omo/cron/registry.yaml` 是**部分视图** —— 已装 crontab
    比它多出 resident daemon 五角色等条目 (check_drift 记为 orphan)。整份
    `generate crontab | crontab -` 会把这些条目**删掉**, 而 resident daemon 是常驻
    Agent 的驱动。装机前跑 `--diff` 就能看见「会删哪几条、会加哪几条」, 再逐条决定
    merge 还是替换。

    与 check_drift 的分工: check_drift 判「登记↔安装是否一致」(drift/orphan),
    本函数只回答「整份替换会改动什么」, 不做判定、不写盘。

    **候选侧必须与 check_drift 同口径展开 `$HOME/Workspace`**: `compile_crontab`
    产出的是登记面原文 (`cd "$HOME/Workspace" && ...`), 而 installed_lines 来自
    crontab (绝对路径)。不展开的话, 每个 `$HOME` 拼法的登记作业都会同时出现在
    removed 与 added 里 —— 实测 23 条「added」**全部**含 `$HOME`, 全是假报
    (同期 check_drift: drift 0 / orphan 3)。
    """
    jobs = _load_jobs()
    candidate = [l for l in compile_crontab(jobs) if l.strip() and not l.startswith("#")]
    if installed_lines is None:
        try:
            r = subprocess.run(["crontab", "-l"], capture_output=True, text=True, timeout=10)
            installed_lines = r.stdout.splitlines() if r.returncode == 0 else []
        except Exception:
            installed_lines = []
    cand_set = {_normalize_interpreter(_expand_workspace(l)) for l in candidate}
    inst_set = set()
    for line in installed_lines:
        s = line.strip()
        if s and not s.startswith("#"):
            inst_set.add(_normalize_interpreter(_normalize_installed_line(s)))
    removed = sorted(inst_set - cand_set)
    added = sorted(cand_set - inst_set)
    return {
        "ok": True,
        "mode": "read_only",
        "removed_count": len(removed),
        "added_count": len(added),
        "removed": removed,
        "added": added,
        "hint": "整份替换会删掉 removed 里的条目; 装机请逐条 merge, 不要直接替换",
    }


def check_drift(installed_lines: list[str] | None = None) -> dict:
    """校验登记源 vs crontab 安装态一致性.

    只比较 status=active 且 planes 含 crontab 的条目; status=proposed 是尚未
    正式启用的治理巡检 backlog, 不该被算成 drift (v2, TASK-B3229A65)。

    `installed_lines`: 安装态注入缝 (测试用)。`None` = 读本机 `crontab -l`。
    不注入时行为逐字节不变; 注入时**不碰本机 crontab**, 于是 `ok` 只由
    「登记 ↔ 编译产物」决定, 不随本机 cron 状态漂移。

    比对键是**归一化整行**。截断 (旧 `[:120]`) 会把 120 字符之后才不同的两条任务
    折成一个键: 于是 `*_count` 欠计真实条数, 且一条 drift 能与一条 orphan 互相
    抵消成 `ok=True` —— 判定塌缩成假绿 (BET-Y2Q4-T10-291)。

    登记侧先过 `_host_scoped` (CRON-REGISTRY-NO-HOST-SCOPE): registry 是跨机并集,
    而本函数判的是**本机**一致性 —— 不过滤时单机专用条目在别的机器上永远 drift。
    """
    registered = _host_scoped(_load_jobs())
    reg_set = set()
    for j in registered:
        if j.get("status", "active") != "active":
            continue
        if "crontab" not in j.get("planes", []):
            continue
        sched, cmd = j.get("schedule", ""), j.get("command", "")
        reg_set.add(f"{sched} {_normalize_interpreter(_expand_workspace(cmd))}")
    if installed_lines is None:
        try:
            r = subprocess.run(["crontab", "-l"], capture_output=True, text=True, timeout=10)
            installed_lines = r.stdout.splitlines() if r.returncode == 0 else []
        except Exception:
            installed_lines = []
    inst_set = set()
    for line in installed_lines:
        s = line.strip()
        if s and not s.startswith("#"):
            inst_set.add(_normalize_interpreter(_normalize_installed_line(s)))

    drift = reg_set - inst_set
    raw_orphan = inst_set - reg_set
    raw_registry = _load_raw()
    known_orphans = [str(k) for k in raw_registry.get("known_orphans", []) if k]
    orphan = {line for line in raw_orphan if not any(k in line for k in known_orphans)}
    ok = not drift and not orphan
    res = {"ok": ok, "drift_count": len(drift), "orphan_count": len(orphan)}
    if known_orphans:
        res["known_orphan_count"] = len(raw_orphan) - len(orphan)
    # T16-01 shadow: launchd 平面只报告, **不参与 ok 判定** (ADR-0457 三段式)
    try:
        res["launchd"] = check_launchd_plane(registered)
    except Exception as exc:  # noqa: BLE001 — shadow 段自身故障不得阻断 crontab 判定
        res["launchd"] = {"mode": "shadow", "blocks_gate": False, "error": str(exc)[:200]}
    # shadow: 登记面钉了解释器但写法折不回裸 python3 ⇒ 该行与安装态永远不可比。
    # 不参与 ok 判定 —— 现有 1 条 (`local-ops-test-all` 钉 dev-venv/bin/python) 是
    # 刻意固定 venv, 翻成阻断会把「口径不可比」误报成「作业坏了」。
    try:
        fold = _unfoldable_interpreter_jobs(registered)
        res["interpreter_fold"] = {
            "mode": "shadow",
            "blocks_gate": False,
            "count": len(fold),
            "entries": fold[:20],
        }
    except Exception as exc:  # noqa: BLE001 — 同上
        res["interpreter_fold"] = {"mode": "shadow", "blocks_gate": False, "error": str(exc)[:200]}
    return res


if __name__ == "__main__":
    # 统一走 main(): 此前本块是**第二套 dispatch**, 与 main() 并存 ⇒ main() 成了
    # 死代码, 任何只加进 main() 的分支 (如 --diff) 在脚本方式下根本走不到。
    # 退出码语义保持不变: --check 漂移 ⇒ 1, 其余 ⇒ 0。
    sys.exit(main())
