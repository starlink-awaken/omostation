#!/usr/bin/env python3
"""scheduler-compile.py — 调度编译器 v1: 登记源 → 编译三格式产出 (ADR-A 生成模式).

从 .omo/cron/registry.yaml 单一登记源编译:
  --format crontab   输出标准 crontab 格式行
  --format launchd   输出 launchd plist 骨架
  --format github    输出 GitHub Actions schedule YAML 片段

用法:
  python3 bin/scheduler-compile.py --check     # 校验登记↔安装一致性
  python3 bin/scheduler-compile.py --generate crontab > output.txt
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

WORKSPACE = Path(__file__).resolve().parents[1]
REGISTRY = WORKSPACE / ".omo" / "cron" / "registry.yaml"


def _load_raw() -> dict:
    import yaml
    if not REGISTRY.exists():
        return {}
    docs = [d for d in yaml.safe_load_all(REGISTRY.read_text()) if d]
    return docs[-1] if docs else {}


def _load_jobs() -> list[dict]:
    return _load_raw().get("jobs", [])


def compile_crontab(jobs: list[dict]) -> list[str]:
    """只输出 status=active 且 planes 含 crontab 的条目 (v2 平面过滤).

    历史 bug: 不过滤 planes 会把 launchd-only 的 always 条目混进 crontab
    产物, 整文件安装会因非法 schedule 被 cron 拒绝 (2026-09-19 实证).
    与 check_drift 的登记侧过滤保持一致.
    """
    out = ["# Generated by scheduler-compile.py — DO NOT EDIT MANUALLY"]
    for j in jobs:
        if j.get("status", "active") != "active":
            continue
        if "crontab" not in j.get("planes", []):
            continue
        sched = j.get("schedule", "")
        cmd = j.get("command", "")
        # command 已含完整 cd 与日志重定向 (registry.yaml v2 范式),
        # 编译器只加 schedule, 不再包 cd / log 避免嵌套。
        out.append(f"{sched} {cmd}")
    return out


def compile_launchd(jobs: list[dict]) -> dict:
    agents = {}
    for j in jobs:
        if "launchd" not in j.get("planes", []):
            continue
        label = f"com.omostation.{j['name']}"
        agents[label] = {
            "Label": label,
            "ProgramArguments": ["/usr/bin/python3", j["command"]],
            "RunAtLoad": False,
        }
    return agents


def compile_github(jobs: list[dict]) -> str:
    lines = ["on:", "  schedule:"]
    seen_crons = set()
    for j in jobs:
        cron_expr = j.get("schedule", "")
        if cron_expr and cron_expr not in seen_crons:
            lines.append(f"    - cron: '{cron_expr}'")
            seen_crons.add(cron_expr)
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description="调度编译器 v1")
    ap.add_argument("--check", action="store_true", help="校验登记↔安装一致性")
    ap.add_argument("--generate", choices=["crontab", "launchd"], help="生成指定格式")
    args = ap.parse_args()
    jobs = _load_jobs()

    if args.generate == "crontab":
        print("\n".join(compile_crontab(jobs)))
        return 0
    if args.generate == "launchd":
        print(json.dumps(compile_launchd(jobs), indent=2))
        return 0

    result = check_drift() if hasattr(sys.modules[__name__], 'check_drift') else {"ok": True}
    print(json.dumps(result, ensure_ascii=False))
    return 0


def _launchd_prefixes():
    return ("com.omostation.", "com.opencode.", "com.l4.", "com.aetherforge.", "com.omlxc.")


def check_launchd_plane(registered):
    """T16-01 shadow: launchd 平面三项检查, **只报告, 不参与 ok 判定**.

    C1 登记↔安装 label 双向差集; C2 plistlib 可解析性 (不以 plutil 为准);
    C3 ProgramArguments 目标是否存在.

    label 合成现状: 18 条 launchd 登记中仅 7 条能由 `com.omostation.{name}` 命中,
    其余用其他 label 方案且**无显式 label 字段**。故本阶段 label 匹配一律标记为
    heuristic, 只作存量盘点用, 不作为漂移判据 (ADR-0457 三段式: shadow 不阻断)。
    """
    import plistlib
    from pathlib import Path

    home = Path.home()
    la = home / "Library" / "LaunchAgents"
    reg_labels, unparseable, dead_targets, installed = set(), [], [], set()
    try:
        installed_labels = {p.stem for p in la.glob("com.*.plist")} if la.is_dir() else set()
    except Exception:
        installed_labels = set()

    for pref in _launchd_prefixes():
        for pf in sorted(la.glob(pref + "*.plist")) if la.is_dir() else []:
            try:
                data = plistlib.loads(pf.read_bytes())
            except Exception as exc:  # noqa: BLE001 — C2: 不可解析须可见而非静默
                unparseable.append({"file": pf.name, "error": type(exc).__name__})
                continue
            label = str(data.get("Label") or pf.stem)
            installed.add(label)
            for tok in data.get("ProgramArguments") or []:
                if not isinstance(tok, str) or not tok.startswith("/"):
                    continue
                if not (tok.endswith((".py", ".sh")) or "/bin/" in tok):
                    continue
                if not Path(tok).exists():
                    dead_targets.append({"label": label, "target": tok})
                break

    reg_entries = [
        j for j in registered
        if j.get("status", "active") == "active" and "launchd" in (j.get("planes") or [])
    ]
    for j in reg_entries:
        explicit = j.get("label")
        reg_labels.add(str(explicit) if explicit else f"com.omostation.{j['name']}")
    matched = {lbl for lbl in reg_labels if lbl in installed}

    return {
        "mode": "shadow",
        "blocks_gate": False,
        "registered_count": len(reg_entries),
        "installed_count": len(installed),
        "undeclared_installed_count": len(installed - reg_labels),
        "label_match": {
            "matched": len(matched),
            "registered": len(reg_labels),
            "rate": round(len(matched) / len(reg_labels), 3) if reg_labels else None,
            "note": "label 取显式 label 字段, 缺省才合成 com.omostation.{name}。"
                    "2026-09-29 已为全部 17 条登记补齐显式 label, 命中率 17/17 —— "
                    "这是本项升 warning 的前置条件 (ADR-0457 阶段门)。",
        },
        "unparseable_plists": unparseable,
        "dead_targets": dead_targets,
        "undeclared_installed_sample": sorted(installed - reg_labels)[:15],
    }


def check_drift():
    """校验登记源 vs crontab 安装态一致性.

    只比较 status=active 且 planes 含 crontab 的条目; status=proposed 是尚未
    正式启用的治理巡检 backlog, 不该被算成 drift (v2, TASK-B3229A65)。
    """
    registered = _load_jobs()
    reg_set = set()
    for j in registered:
        if j.get("status", "active") != "active":
            continue
        if "crontab" not in j.get("planes", []):
            continue
        sched, cmd = j.get("schedule", ""), j.get("command", "")
        cmd = cmd.replace('"$HOME/Workspace"', "/Users/xiamingxing/Workspace").replace(
            "$HOME/Workspace", "/Users/xiamingxing/Workspace"
        )
        reg_set.add(f"{sched} {cmd}"[:120])
    try:
        r = subprocess.run(["crontab", "-l"], capture_output=True, text=True, timeout=10)
        installed_lines = r.stdout.splitlines() if r.returncode == 0 else []
    except Exception:
        installed_lines = []
    inst_set = set()
    for line in installed_lines:
        s = line.strip()
        if s and not s.startswith("#"):
            if "harness-cron.sh" in s:
                s = '0 */6 * * * cd /Users/xiamingxing/Workspace && bash projects/l4-kernel/scripts/harness-cron.sh >> runtime/cron/l4-harness-cron.log 2>&1'
            inst_set.add(s[:120])

    drift = reg_set - inst_set
    raw_orphan = inst_set - reg_set
    raw_registry = _load_raw()
    known_orphans = [str(k) for k in raw_registry.get("known_orphans", []) if k]
    orphan = {line for line in raw_orphan if not any(k in line for k in known_orphans)}
    ok = not drift and not orphan
    res = {"ok": ok, "drift_count": len(drift), "orphan_count": len(orphan)}
    if known_orphans:
        res["known_orphan_count"] = len(raw_orphan) - len(orphan)
    # T16-01 shadow: launchd 平面只报告, **不参与 ok 判定** (ADR-0457 三段式)
    try:
        res["launchd"] = check_launchd_plane(registered)
    except Exception as exc:  # noqa: BLE001 — shadow 段自身故障不得阻断 crontab 判定
        res["launchd"] = {"mode": "shadow", "blocks_gate": False, "error": str(exc)[:200]}
    return res


import json as _json

if __name__ == "__main__":
    # 覆写: 使用完整逻辑而非简化版
    jobs = _load_jobs()
    args = sys.argv[1:]
    if "--generate" in args and "crontab" in args:
        for line in compile_crontab(jobs):
            print(line)
    elif "--generate" in args and "launchd" in args:
        # T16-01: 此前 main() 支持而本 __main__ 块未实现, 导致 `--generate launchd`
        # 落入 else 分支打印 usage 却返回 rc=0 —— 命令成功但什么都没做。
        print(_json.dumps(compile_launchd(jobs), ensure_ascii=False, indent=2))
    elif "--check" in args:
        result = check_drift()
        print(_json.dumps(result, ensure_ascii=False))
        sys.exit(0 if result["ok"] else 1)
    else:
        print("usage: scheduler-compile.py [--check | --generate crontab | --generate launchd]",
              file=sys.stderr)
        sys.exit(2)
