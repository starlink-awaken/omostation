def slugify(text: str) -> str:
    """生成 scene_id 友好 slug. camelCase / dot.notation → kebab-case."""
    # XMLParser → XML-Parser → xml-parser
    text = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1-\2", text)
    text = re.sub(r"([a-z])([A-Z])", r"\1-\2", text)
    text = re.sub(r"[^a-zA-Z0-9\s-]", "-", text)
    text = re.sub(r"[\s_]+", "-", text.strip().lower())
    text = re.sub(r"-+", "-", text)
    return text.strip("-")[:50]


def infer_scene_class(domain: str | None) -> str:
    """基于 domain 推断 scene_class."""
    if domain in ("work", "health", "research", "knowledge"):
        return "business"
    if domain in ("governance",):
        return "governance"
    return "infra"


def infer_scene_type(description: str | None) -> str:
    """基于 description 推断 scene_type."""
    if not description:
        return "inbound"
    desc = description.lower()
    if any(kw in desc for kw in ["分类", "classify", "识别"]):
        return "inbound"
    if any(kw in desc for kw in ["生成", "produce", "创建"]):
        return "outbound"
    if any(kw in desc for kw in ["周期", "定期", "cron", "schedule"]):
        return "cycle"
    return "inbound"


def scaffold_scene(
    scene_id: str,
    domain: str,
    description: str,
    consumer: str = "xiamingxing",
    trigger: str | None = None,
) -> dict[str, Any]:
    """生成 scene-card/v3 草稿."""
    scene = {k: v for k, v in DEFAULT_TEMPLATE.items() if k != "scene_id"}
    scene["scene_id"] = scene_id
    scene["domain"] = domain
    scene["scene_class"] = infer_scene_class(domain)
    scene["scene_type"] = infer_scene_type(description)
    scene["description"] = description
    scene["name"] = scene_id.replace("-", " ").title()
    scene["trigger"] = trigger or "（待填）"
    scene["consumer"] = consumer
    scene["operator"] = f"{scene_id}-dispatch"
    scene["input_contract"] = "（待填：触发时输入字段）"
    scene["result_contract"] = "（待填：输出字段）"
    scene["outcome_metric"] = f"{scene_id.replace('-', '_')}_accuracy"
    scene["failure_cost"] = "场景输出错误导致下游流程走错分支"
    scene["notes"] = [
        f"Auto-generated by scene-card-autogen.py at {scene.get('notes', ['(unfilled)'])[0] if scene.get('notes') else 'now'}",
    ]
    return scene


def from_signal(signal: str) -> dict[str, Any]:
    """从信号 (e.g. 'email.received:invoice') 推断 scene."""
    if ":" in signal:
        sig_type, filter_str = signal.split(":", 1)
    else:
        sig_type, filter_str = signal, ""
    domain = "work"
    if "email" in sig_type:
        domain = "work"
    elif "file" in sig_type:
        domain = "knowledge"
    elif "calendar" in sig_type:
        domain = "work"
    elif "commit" in sig_type:
        domain = "governance"
    scene_id = slugify(f"{sig_type}-{filter_str}" if filter_str else sig_type)
    description = (
        f"对 {sig_type} 信号"
        + (f" (filter: {filter_str})" if filter_str else "")
        + " 触发场景, 处理后路由到下游"
    )
    return scaffold_scene(scene_id, domain, description, trigger=signal)


def yaml_dump(scene: dict[str, Any]) -> str:
    """序列化为 YAML 字符串."""
    if yaml is None:
        # 简化输出 (无 PyYAML)
        lines = []
        for k, v in scene.items():
            if isinstance(v, dict):
                lines.append(f"{k}:")
                for kk, vv in v.items():
                    lines.append(f"  {kk}: {_yaml_inline(vv)}")
            elif isinstance(v, list):
                lines.append(f"{k}:")
                for item in v:
                    lines.append(f"  - {_yaml_inline(item)}")
            else:
                lines.append(f"{k}: {_yaml_inline(v)}")
        return "\n".join(lines) + "\n"
    return yaml.safe_dump(scene, allow_unicode=True, sort_keys=False, default_flow_style=False)


def _yaml_inline(v: Any) -> str:
    """简化标量 YAML 字符串."""
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    s = str(v)
    # 引号转义
    if any(c in s for c in [":", "#", "&", "*", "!", "|", ">", "%", "@", "`"]) or s.startswith(
        ("-", "?", "[", "]", "{", "}", ",", "&", "*", "!")
    ):
        return f'"{s}"'
    if "\n" in s:
        return "|\n" + "\n".join(f"  {ln}" for ln in s.splitlines())
    return s


def list_templates() -> list[dict[str, Any]]:
    """列出 scenes/v3 现有 scenes, 提取 pattern."""
    if not SCENES_DIR.exists() or yaml is None:
        return []
    out = []
    for path in SCENES_DIR.glob("scene-*.yaml"):
        try:
            data = yaml.safe_load(path.read_text(encoding="utf-8"))
        except Exception:
            continue
        if isinstance(data, dict):
            out.append({
                "file": path.name,
                "scene_id": data.get("scene_id", ""),
                "domain": data.get("domain", ""),
                "scene_class": data.get("scene_class", ""),
                "scene_type": data.get("scene_type", ""),
                "lifecycle": data.get("lifecycle", ""),
            })
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p_scaffold = sub.add_parser("scaffold", help="生成空白 scene 草稿")
    p_scaffold.add_argument("--scene-id", required=True)
    p_scaffold.add_argument("--domain", required=True, choices=["work", "health", "research", "knowledge", "governance"])
    p_scaffold.add_argument("--description", required=True)
    p_scaffold.add_argument("--consumer", default="xiamingxing")
    p_scaffold.add_argument("--trigger")
    p_scaffold.add_argument("--out", help="输出 YAML 路径 (默认 stdout)")

    p_sig = sub.add_parser("from-signal", help="从信号生成 scene")
    p_sig.add_argument("--signal", required=True)
    p_sig.add_argument("--out")

    p_list = sub.add_parser("list-templates", help="列出已有 scene 模板")

    args = ap.parse_args()

    if args.cmd == "scaffold":
        scene = scaffold_scene(
            scene_id=args.scene_id,
            domain=args.domain,
            description=args.description,
            consumer=args.consumer,
            trigger=args.trigger,
        )
        output = yaml_dump(scene)
        if args.out:
            Path(args.out).write_text(output, encoding="utf-8")
            print(f"✅ 写入: {args.out}")
        else:
            print(output)
    elif args.cmd == "from-signal":
        scene = from_signal(args.signal)
        output = yaml_dump(scene)
        if args.out:
            Path(args.out).write_text(output, encoding="utf-8")
            print(f"✅ 写入: {args.out}")
        else:
            print(output)
    elif args.cmd == "list-templates":
        templates = list_templates()
        if not templates:
            print("⚠️ 无现有 scene 模板或 PyYAML 不可用")
            return 1
        print(f"━━━ 现有 scenes ({len(templates)} 个) ━━━")
        for t in templates:
            print(f"  {t['scene_id']:<35} {t['domain']:<12} {t['lifecycle']:<10} {t['scene_type']:<10}")
        return 0
    return 0


if __name__ == "__main__":
    sys.exit(main())