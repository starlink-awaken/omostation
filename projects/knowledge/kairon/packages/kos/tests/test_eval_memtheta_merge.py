import os

import pytest
from deepeval import assert_test
from deepeval.metrics import ContextualRelevancyMetric, FaithfulnessMetric
from deepeval.test_case import LLMTestCase

# This ensures DeepEval uses the local Langfuse deployment if tokens are provided
# In production, these should be securely injected via .env or secrets manager
os.environ.setdefault("LANGFUSE_HOST", "http://localhost:3000")
# We use dummy keys if not set so the test doesn't crash in CI without keys
os.environ.setdefault("LANGFUSE_PUBLIC_KEY", "pk-lf-dummy")
os.environ.setdefault("LANGFUSE_SECRET_KEY", "sk-lf-dummy")


def test_memtheta_merge_quality():
    """
    LLM-as-Judge Evaluation (eCOS v6.1 Phase 2 T2.3)
    Evaluates the 'Merge' operator's `distilled_context` output against the input fragments
    to ensure Faithfulness (no hallucinations) and Contextual Relevancy.
    """

    # Mock inputs (In a real scenario, we extract these from the OTLP trace payload)
    input_fragments = [
        "User prefers using React for frontend development.",
        "User wants to avoid TailwindCSS and use Vanilla CSS instead.",
        "User values high-performance web applications.",
    ]

    # The output generated by our LLM during a MemTheta merge operation
    actual_output = (
        "The user is a frontend developer who prefers building high-performance "
        "web applications using React and Vanilla CSS. They strictly avoid TailwindCSS."
    )

    # Retrieval Context used to ground the LLM's response
    retrieval_context = input_fragments

    test_case = LLMTestCase(
        input="Summarize the user's frontend preferences.",
        actual_output=actual_output,
        retrieval_context=retrieval_context,  # type: ignore[reportArgumentType]
    )

    # If the workspace doesn't have an OpenAI key injected, we skip the actual remote LLM call
    # so we don't break the CI pipeline. In a real vibeops environment, this runs.
    if not os.environ.get("OPENAI_API_KEY"):
        pytest.skip("Skipping LLM-as-Judge evaluation: OPENAI_API_KEY not set.")

    # Metric 1: Faithfulness - Check if the output contains hallucinated facts not in context
    faithfulness_metric = FaithfulnessMetric(
        threshold=0.8,
        model="gpt-4o",  # or the local model we use in the workspace
        include_reason=True,
    )

    # Metric 2: Contextual Relevancy - Check if the output answers the input effectively
    relevancy_metric = ContextualRelevancyMetric(threshold=0.8, model="gpt-4o", include_reason=True)

    # Run the hybrid assertion.
    # DeepEval will automatically emit trace scores to Langfuse via its native integration.
    assert_test(test_case, [faithfulness_metric, relevancy_metric])
