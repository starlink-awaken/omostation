def _mutation_surface_category_counts(items: list[dict[str, object]]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for item in items:
        category = str(item.get("category", "unclassified"))
        counts[category] = counts.get(category, 0) + 1
    return dict(sorted(counts.items()))


