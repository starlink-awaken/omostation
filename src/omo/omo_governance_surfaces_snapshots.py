def _worker_profile_subtype_counts(
    items: list[dict[str, object]],
) -> dict[str, int]:
    counts: dict[str, int] = {}
    for item in items:
        subtype = str(item.get("subtype", "unknown"))
        counts[subtype] = counts.get(subtype, 0) + 1
    return dict(sorted(counts.items()))
